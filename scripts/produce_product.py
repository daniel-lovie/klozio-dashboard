#!/usr/bin/env python3
"""Take one approved product from copy to publish-ready images. The ONE entrypoint for that.

    python3 scripts/produce_product.py <product_id>

Approving a product used to change a flag and nothing else: the artwork had to be generated by hand on
the operator's machine, so an approved product sat with `design_state=NULL` and no images until somebody
remembered. The agent could not do it either — there was no path, only a prompt line saying so. For a
product other people pay for, that is not a gap in automation, it is the absence of the product.

This script is called by three callers and does the same thing for all of them, deliberately: the
scheduler's producer tick, the agent's `produce` tool, and the operator on a terminal. Two paths that
both build a listing image is exactly the defect that shipped a whole catalogue at the wrong scale.

Steps, all resumable — anything already done is skipped, so a re-run after a crash costs nothing:
  1. design    Higgsfield generates the artwork from products.design_prompt (the paid step, ~$0.03)
  2. cutout    background keyed locally, transparent pixels decontaminated (free)
  3. palette   embroidery only: colours snapped to the declared thread hexes
  4. print_file written to the DB, which is what the digitiser and the compositor read
  5. images    scripts/produce_images.py builds the 7-9 listing frames
  6. ready     design_state='ready'
"""
